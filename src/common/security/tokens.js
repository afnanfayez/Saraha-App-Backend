import { createHash, randomBytes, randomUUID } from "node:crypto";
import jwt from "jsonwebtoken";
import { env } from "../../config/env.js";

export function hashOpaqueToken(token) {
  return createHash("sha256").update(token, "utf8").digest("hex");
}

export function createOpaqueToken() {
  return randomBytes(48).toString("base64url");
}

export function signAccessToken(userId, role, sessionId) {
  return jwt.sign({ sid: String(sessionId), role, tokenType: "access" }, env.accessSecret, {
    algorithm: "HS256",
    subject: String(userId),
    issuer: env.jwtIssuer,
    audience: env.jwtAudience,
    expiresIn: env.accessTokenTtl,
    jwtid: randomUUID()
  });
}

export function verifyAccessToken(token) {
  return jwt.verify(token, env.accessSecret, {
    algorithms: ["HS256"],
    issuer: env.jwtIssuer,
    audience: env.jwtAudience
  });
}

// This reads claims from a token generated by this application to report its actual lifetime.
// It is not used to authenticate incoming requests; incoming tokens always go through verifyAccessToken.
export function getAccessTokenTtlSeconds(token) {
  const claims = jwt.decode(token);
  if (!claims || typeof claims.iat !== "number" || typeof claims.exp !== "number") {
    throw new Error("Unable to determine the generated access token lifetime");
  }
  return claims.exp - claims.iat;
}

export function createRefreshExpiry(now = new Date()) {
  return new Date(now.getTime() + env.refreshTokenTtlDays * 24 * 60 * 60 * 1000);
}
